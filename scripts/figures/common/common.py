def day_grid_rows(grid: pd.DataFrame, date: str) -> list[dict]:
    sub = grid[grid["date"] == str(date)]
    return [dict(eps=float(r.eps), min_samples=int(r.min_samples),
                 n_components=int(r.n_components))
            for r in sub.itertuples()]


def load_labels_A() -> pd.DataFrame:
    """Per-day heatwave-labelled grid cells with per-cell component labels."""
    df = pd.read_csv(LABELS_A_CSV)
    df["date"] = df["date"].astype(str)
    return df


def day_cells(labels: pd.DataFrame, date: str):
    """All exceedance-grid cell coordinates (lon, lat) for one day."""
    sub = labels[labels["date"] == str(date)]
    return sub["lon"].to_numpy(float), sub["lat"].to_numpy(float)


