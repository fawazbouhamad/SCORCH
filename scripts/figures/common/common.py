def build_event_day_table(df: pd.DataFrame | None = None) -> pd.DataFrame:
    """One row per unique (event, calendar day) with the day-level parameters.

    Verifies that repeated ellipse rows within an event-day agree on the
    selected EPS / min_samples and flags any that do not.
    """
    if df is None:
        df = load_workbook()
    rows = []
    for (eid, date), g in df.groupby(["new_event_id", "date"], sort=True):
        eps_vals = g["dbscan_avg_eps"].round(9).nunique()
        mp_vals = g["dbscan_rounded_minpts"].nunique()
        raw_vals = g["dbscan_raw_avg_minpts"].round(9).nunique()
        conflict = int(eps_vals > 1 or mp_vals > 1 or raw_vals > 1)
        rows.append(dict(
            new_event_id=int(eid),
            event_id=int(g["event_id"].iloc[0]),
            date=pd.Timestamp(date).strftime("%Y-%m-%d"),
            v3_type=int(g["v3_type"].iloc[0]),
            event_type=str(g["type"].iloc[0]),
            event_type_name=str(g["event_type_name"].iloc[0]),
            duration_days=int(g["duration_days"].iloc[0]),
            day_index_in_event=int(g["day_index_in_event"].iloc[0]),
            eps_selected=float(g["dbscan_avg_eps"].iloc[0]),
            min_samples_raw=float(g["dbscan_raw_avg_minpts"].iloc[0]),
            min_samples_selected=int(g["dbscan_rounded_minpts"].iloc[0]),
            modal_count=str(g["dbscan_modal_count"].iloc[0]),
            modal_count_max=max(_parse_int_set(g["dbscan_modal_count"].iloc[0])),
            is_modal_tie=int(len(_parse_int_set(g["dbscan_modal_count"].iloc[0])) > 1),
            n_ellipse_rows=int(g.shape[0]),
            n_unique_ellipses=int(g["cluster_id"].nunique()),
            day_final_n_clusters=int(g["day_final_n_clusters"].iloc[0]),
            source_sheet=WORKBOOK_SHEET,
            param_conflict_flag=conflict,
        ))
    out = pd.DataFrame(rows).sort_values(["date", "new_event_id"]).reset_index(
        drop=True)
    return out


# --- canonical Method-A selection (faithful copy of Phase 25 select_modal) ---
def _parse_int_set(val) -> list[int]:
    """Parse a modal-count cell that may be an int or a '1|2' tie string."""
    s = str(val).strip()
    if s in ("", "nan", "None"):
        return [0]
    out = []
    for tok in s.replace(",", "|").split("|"):
        tok = tok.strip()
        if tok and tok.lower() != "nan":
            try:
                out.append(int(float(tok)))
            except ValueError:
                pass
    return out or [0]


def round_half_up(x: float) -> int:
    return int(math.floor(float(x) + 0.5))


def select_modal(grid_rows: list[dict]) -> dict:
    """Modal-count selection with the canonical tie-averaging rule.

    grid_rows: list of dicts with keys 'eps', 'min_samples', 'n_components'.
    """
    counts = [r["n_components"] for r in grid_rows]
    nonzero = [c for c in counts if c > 0]
    pool = nonzero if nonzero else counts
    freq = Counter(pool)
    maxf = max(freq.values())
    tied = sorted([v for v, f in freq.items() if f == maxf])
    combos = [r for r in grid_rows if r["n_components"] in tied]
    avg_eps = float(np.mean([r["eps"] for r in combos]))
    raw_ms = float(np.mean([r["min_samples"] for r in combos]))
    rounded_ms = max(1, round_half_up(raw_ms))
    return dict(modal_counts=tied, n_modal_values=len(tied),
                is_tie=int(len(tied) > 1), modal_frequency=int(maxf),
                n_combos_averaged=len(combos),
                avg_eps=avg_eps, raw_avg_min_samples=raw_ms,
                rounded_min_samples=rounded_ms)


